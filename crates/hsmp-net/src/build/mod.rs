//! Build identity: what a component was built as, and how two of them compare.
//!
//! Every HSMP component (server, sidecar, native module, Lua mods) carries the same
//! fields: the release version, the wire protocol range, the IPC ABI and layout hash,
//! and the content hash of the shipped mods and server data (`content`). The Rust
//! binaries embed theirs at compile time; deploy and release write the mods' copy
//! (`hsmp_build_id.lua` in every mod, `hsmp/build.json` for the launcher).

pub mod content;

use std::cmp::Ordering;

/// This crate's version, which is the workspace (release) version.
pub const RELEASE_VERSION: &str = env!("CARGO_PKG_VERSION");
/// Product name shown to players.
pub const PRODUCT: &str = "HalfSword-MP";

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Identity {
    pub version: String,
    pub protocol: u16,
    pub proto_min: u16,
    pub proto_max: u16,
    pub ipc_abi_major: u16,
    pub ipc_abi_minor: u16,
    pub ipc_layout: u64,
    pub content_hash: [u8; 32],
}

fn hex(b: &[u8]) -> String {
    b.iter().map(|x| format!("{x:02x}")).collect()
}

/// 64 lowercase hex chars -> 32 bytes.
pub fn parse_hash(s: &str) -> Option<[u8; 32]> {
    let s = s.trim();
    if s.len() != 64 || !s.bytes().all(|c| c.is_ascii_hexdigit()) {
        return None;
    }
    let mut out = [0u8; 32];
    for (i, o) in out.iter_mut().enumerate() {
        *o = u8::from_str_radix(&s[i * 2..i * 2 + 2], 16).ok()?;
    }
    Some(out)
}

/// A version string safe to print anywhere (Lua, JSON, cmd lines).
pub fn version_is_clean(v: &str) -> bool {
    !v.is_empty() && v.len() <= 32 && v.chars().all(|c| c.is_ascii_alphanumeric() || ".-+".contains(c))
}

impl Identity {
    pub fn content_hex(&self) -> String {
        hex(&self.content_hash)
    }

    /// One JSON object (`hsmp/build.json`, `--build-info`).
    pub fn to_json(&self) -> String {
        format!(
            "{{\"product\":\"{PRODUCT}\",\"version\":\"{}\",\"protocol\":{},\"proto_min\":{},\"proto_max\":{},\"ipc_abi_major\":{},\"ipc_abi_minor\":{},\"ipc_layout\":\"{:016x}\",\"content_hash\":\"{}\"}}",
            self.version_safe(), self.protocol, self.proto_min, self.proto_max, self.ipc_abi_major, self.ipc_abi_minor, self.ipc_layout, self.content_hex()
        )
    }

    /// The Lua module every mod ships (`hsmp_build_id.lua`).
    pub fn to_lua(&self) -> String {
        format!(
            "-- Generated by deploy / release: the identity of these mod files. Do not edit.\nreturn {{\n    product = \"{PRODUCT}\",\n    version = \"{}\",\n    protocol = {},\n    proto_min = {},\n    proto_max = {},\n    ipc_abi_major = {},\n    ipc_abi_minor = {},\n    ipc_layout = \"{:016x}\",\n    content_hash = \"{}\",\n}}\n",
            self.version_safe(), self.protocol, self.proto_min, self.proto_max, self.ipc_abi_major, self.ipc_abi_minor, self.ipc_layout, self.content_hex()
        )
    }

    fn version_safe(&self) -> &str {
        if version_is_clean(&self.version) { &self.version } else { "invalid" }
    }

    /// Names of the fields that make `other` unusable with `self` (empty = compatible).
    pub fn differences(&self, other: &Identity) -> Vec<&'static str> {
        let mut d = Vec::new();
        if self.version != other.version {
            d.push("version");
        }
        if self.proto_max < other.proto_min || other.proto_max < self.proto_min {
            d.push("protocol");
        }
        if self.ipc_abi_major != other.ipc_abi_major || self.ipc_layout != other.ipc_layout {
            d.push("ipc");
        }
        if self.content_hash != other.content_hash {
            d.push("content");
        }
        d
    }
}

/// The release version a Hello's build string carries ("hsmp-sidecar 0.1.0" -> "0.1.0").
pub fn version_of_build(build: &str) -> Option<&str> {
    let v = build.split_whitespace().last()?;
    parse_version(v).map(|_| v)
}

type Parsed<'a> = ([u64; 3], Option<&'a str>);

fn parse_version(v: &str) -> Option<Parsed<'_>> {
    let v = v.strip_prefix('v').unwrap_or(v);
    let v = v.split('+').next()?;
    let (core, pre) = match v.split_once('-') {
        Some((c, p)) => (c, Some(p)),
        None => (v, None),
    };
    let mut n = [0u64; 3];
    let parts: Vec<&str> = core.split('.').collect();
    if parts.is_empty() || parts.len() > 3 {
        return None;
    }
    for (i, p) in parts.iter().enumerate() {
        n[i] = p.parse().ok()?;
    }
    Some((n, pre.filter(|p| !p.is_empty())))
}

/// Semver order of two release versions (`None` when either does not parse).
pub fn cmp_versions(a: &str, b: &str) -> Option<Ordering> {
    let (na, pa) = parse_version(a)?;
    let (nb, pb) = parse_version(b)?;
    Some(na.cmp(&nb).then_with(|| match (pa, pb) {
        (None, None) => Ordering::Equal,
        (None, Some(_)) => Ordering::Greater,
        (Some(_), None) => Ordering::Less,
        (Some(x), Some(y)) => cmp_pre(x, y),
    }))
}

fn cmp_pre(a: &str, b: &str) -> Ordering {
    let mut ia = a.split('.');
    let mut ib = b.split('.');
    loop {
        match (ia.next(), ib.next()) {
            (None, None) => return Ordering::Equal,
            (None, Some(_)) => return Ordering::Less,
            (Some(_), None) => return Ordering::Greater,
            (Some(x), Some(y)) => {
                let o = match (x.parse::<u64>(), y.parse::<u64>()) {
                    (Ok(p), Ok(q)) => p.cmp(&q),
                    (Ok(_), Err(_)) => Ordering::Less,
                    (Err(_), Ok(_)) => Ordering::Greater,
                    _ => x.cmp(y),
                };
                if o != Ordering::Equal {
                    return o;
                }
            }
        }
    }
}

/// Why a server refused a client's build.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Mismatch {
    /// No common wire protocol.
    Protocol { client_older: bool },
    /// Same protocol, different mod files / server data.
    Content,
}

/// The reject text a client shows (fits the 120-byte link reason for normal versions).
pub fn reject_text(m: Mismatch, server_version: &str, client_build: &str) -> String {
    let theirs = version_of_build(client_build).unwrap_or("an older build");
    let head = format!("Server runs {PRODUCT} {server_version}, you have {theirs}.");
    let client_older = match m {
        Mismatch::Protocol { client_older } => Some(client_older),
        Mismatch::Content => version_of_build(client_build).and_then(|c| cmp_versions(c, server_version)).and_then(|o| match o {
            Ordering::Less => Some(true),
            Ordering::Greater => Some(false),
            Ordering::Equal => None,
        }),
    };
    match (m, client_older) {
        (_, Some(true)) => format!("{head} Your mod is OUTDATED: update via the launcher."),
        (_, Some(false)) => format!("{head} The server is outdated: ask the host to update."),
        (Mismatch::Content, None) => format!("{head} Your mod files differ: repair via the launcher."),
        (Mismatch::Protocol { .. }, None) => format!("{head} Protocol mismatch: update via the launcher."),
    }
}

#[cfg(test)]
mod tests {
    use super::content::*;
    use super::*;
    use std::collections::BTreeMap;

    struct Mem(BTreeMap<String, Vec<u8>>);
    impl Source for Mem {
        fn files(&self, dir: &str) -> Vec<String> {
            let pre = format!("{dir}/");
            self.0.keys().filter(|k| k.starts_with(&pre) && !k[pre.len()..].contains('/')).cloned().collect()
        }
        fn read(&self, path: &str) -> Option<Vec<u8>> {
            self.0.get(path).cloned()
        }
    }

    fn tree() -> Mem {
        let mut m = BTreeMap::new();
        m.insert(TEMPLATE.into(), b"# x\nHSMPA : 1\nHSMPB : 0\nHSMPNative : 1\nHSMPDiag : dev\nKeybinds : dev\n".to_vec());
        m.insert("mods/HSMPA/Scripts/main.lua".into(), b"print(1)\n".to_vec());
        m.insert("mods/HSMPA/Scripts/x.lua".into(), b"return 2\n".to_vec());
        m.insert("mods/HSMPA/Scripts/notes.txt".into(), b"ignored".to_vec());
        m.insert("mods/HSMPA/Scripts/sub/deep.lua".into(), b"ignored".to_vec());
        m.insert("mods/HSMPB/Scripts/main.lua".into(), b"disabled".to_vec());
        m.insert("mods/shared/hsmp_cfg.lua".into(), b"return {}\n".to_vec());
        m.insert("server/data/maps/Map_Arena_Pit.json".into(), b"{}\n".to_vec());
        Mem(m)
    }

    #[test]
    fn content_set_is_the_release_payload() {
        let (_, paths) = content_hash(&tree()).unwrap();
        assert_eq!(
            paths,
            vec![
                "mods/HSMPA/Scripts/main.lua",
                "mods/HSMPA/Scripts/x.lua",
                "mods/mods.release.txt",
                "mods/shared/hsmp_cfg.lua",
                "server/data/maps/Map_Arena_Pit.json",
            ]
        );
        assert_eq!(enabled_mods("HSMPA : 1\nHSMPB:1\n# HSMPC : 1\nOther : 1\nHSMPD : dev"), vec!["HSMPA", "HSMPB"]);
    }

    #[test]
    fn content_hash_ignores_crlf_and_tracks_every_file() {
        let base = content_hash(&tree()).unwrap().0;
        let mut crlf = tree();
        crlf.0.insert("mods/HSMPA/Scripts/main.lua".into(), b"print(1)\r\n".to_vec());
        assert_eq!(content_hash(&crlf).unwrap().0, base, "line endings do not matter");
        let mut edit = tree();
        edit.0.insert("mods/shared/hsmp_cfg.lua".into(), b"return { x = 1 }\n".to_vec());
        assert_ne!(content_hash(&edit).unwrap().0, base);
        let mut map = tree();
        map.0.insert("server/data/maps/Map_Arena_Yard.json".into(), b"{}\n".to_vec());
        assert_ne!(content_hash(&map).unwrap().0, base, "a new map changes the hash");
        let mut off = tree();
        off.0.insert("mods/HSMPB/Scripts/main.lua".into(), b"changed".to_vec());
        assert_eq!(content_hash(&off).unwrap().0, base, "disabled mods are not content");
        let mut moved = tree();
        let v = moved.0.remove("mods/HSMPA/Scripts/x.lua").unwrap();
        moved.0.insert("mods/HSMPA/Scripts/y.lua".into(), v);
        assert_ne!(content_hash(&moved).unwrap().0, base, "paths are hashed");
        assert!(content_hash(&Mem(BTreeMap::new())).is_none());
    }

    #[test]
    fn this_checkout_hashes() {
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
        let (h, paths) = content_hash(&FsSource(root)).unwrap();
        assert!(paths.iter().any(|p| p == "mods/HSMPMenu/Scripts/main.lua"), "{paths:?}");
        assert!(paths.iter().any(|p| p.starts_with("server/data/maps/")));
        assert_ne!(h, [0; 32]);
    }

    fn id() -> Identity {
        Identity {
            version: "0.1.0-beta.1".into(),
            protocol: 6,
            proto_min: 6,
            proto_max: 6,
            ipc_abi_major: 2,
            ipc_abi_minor: 0,
            ipc_layout: 0xabc,
            content_hash: [7; 32],
        }
    }

    #[test]
    fn identity_compare() {
        let a = id();
        assert!(a.differences(&a).is_empty());
        let mut b = id();
        b.ipc_abi_minor = 1;
        assert!(a.differences(&b).is_empty(), "a minor IPC bump is compatible");
        b.version = "0.1.0".into();
        b.content_hash = [8; 32];
        assert_eq!(a.differences(&b), vec!["version", "content"]);
        let mut c = id();
        c.proto_min = 7;
        c.proto_max = 8;
        c.ipc_layout = 1;
        assert_eq!(a.differences(&c), vec!["protocol", "ipc"]);
        let mut r = id();
        r.proto_min = 5;
        r.proto_max = 7;
        assert!(a.differences(&r).is_empty(), "overlapping protocol ranges are compatible");
    }

    #[test]
    fn identity_renders() {
        let j = id().to_json();
        assert!(j.contains("\"version\":\"0.1.0-beta.1\"") && j.contains("\"protocol\":6") && j.contains("\"ipc_layout\":\"0000000000000abc\""), "{j}");
        assert!(j.contains(&format!("\"content_hash\":\"{}\"", "07".repeat(32))));
        let l = id().to_lua();
        assert!(l.contains("version = \"0.1.0-beta.1\"") && l.contains("protocol = 6"), "{l}");
        let mut bad = id();
        bad.version = "x\"); os.exit(".into();
        assert!(bad.to_lua().contains("version = \"invalid\""));
        assert_eq!(parse_hash(&"07".repeat(32)), Some([7; 32]));
        assert_eq!(parse_hash("07"), None);
        assert_eq!(parse_hash(&"zz".repeat(32)), None);
    }

    #[test]
    fn versions_order_like_semver() {
        use Ordering::*;
        assert_eq!(cmp_versions("0.1.0", "0.1.0"), Some(Equal));
        assert_eq!(cmp_versions("0.1.0-beta.1", "0.1.0"), Some(Less));
        assert_eq!(cmp_versions("0.1.0-beta.2", "0.1.0-beta.10"), Some(Less));
        assert_eq!(cmp_versions("0.1.0-beta.1", "0.1.0-alpha.9"), Some(Greater));
        assert_eq!(cmp_versions("0.2", "0.1.9"), Some(Greater));
        assert_eq!(cmp_versions("v1.0.0", "0.9.0"), Some(Greater));
        assert_eq!(cmp_versions("x", "0.1.0"), None);
        assert_eq!(version_of_build("hsmp-sidecar 0.1.0-beta.1"), Some("0.1.0-beta.1"));
        assert_eq!(version_of_build("loadtest"), None);
        assert_eq!(version_of_build(""), None);
    }

    #[test]
    fn reject_texts_name_both_versions_and_a_fix() {
        let t = reject_text(Mismatch::Protocol { client_older: true }, "0.2.0", "hsmp-sidecar 0.1.0");
        assert_eq!(t, "Server runs HalfSword-MP 0.2.0, you have 0.1.0. Your mod is OUTDATED: update via the launcher.");
        let t = reject_text(Mismatch::Protocol { client_older: false }, "0.1.0", "hsmp-sidecar 0.2.0");
        assert!(t.contains("server is outdated"), "{t}");
        let t = reject_text(Mismatch::Content, "0.1.0", "hsmp-sidecar 0.1.0");
        assert!(t.contains("files differ") && t.contains("repair"), "{t}");
        let t = reject_text(Mismatch::Content, "0.1.1", "hsmp-sidecar 0.1.0");
        assert!(t.contains("OUTDATED"), "{t}");
        let t = reject_text(Mismatch::Protocol { client_older: true }, "0.1.0", "");
        assert!(t.contains("you have an older build"), "{t}");
        let long = reject_text(Mismatch::Protocol { client_older: true }, "0.10.10-beta.10", "hsmp-sidecar 0.10.10-beta.10");
        assert!(long.len() <= 120, "fits the link reason: {} bytes", long.len());
    }
}
